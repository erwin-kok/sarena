use std::net::{Ipv4Addr, Ipv6Addr};

use ipnet::{Ipv4Net, Ipv6Net};
use sarena_infra::NetworkProvisioner;
use tracing::{info, warn};

use crate::{
    config::{Config, Ipv6Prefix64},
    node::LocalNode,
};

/// Node IPv6 address used when the system has no global IPv6 address.
pub const DEFAULT_IPV6_HOST_ADDRESS: Ipv6Addr = Ipv6Addr::new(0xfc00, 0, 0, 0, 0, 0, 0x10ca, 1);

impl LocalNode {
    /// Fills in the node's addresses and allocation ranges that aren't set
    /// yet with defaults derived from the system.
    ///
    /// `device` can name the system's primary network device, in which case
    /// its first global address is used as the node address (see
    /// [`NetworkProvisioner::first_global_ipv4`]).
    pub async fn initialize(
        &mut self,
        network_provisioner: &impl NetworkProvisioner,
        config: &Config,
        device: Option<&str>,
    ) -> anyhow::Result<()> {
        if config.enable_ipv4 {
            let global_ipv4 = network_provisioner
                .first_global_ipv4(device, self.ipv4_internal_address)
                .await?;

            self.ipv4_external_address.get_or_insert(global_ipv4);

            if self.ipv4_allocation_range.is_none() {
                // Derive it from the IPv6 range when there is one, so the two
                // ranges of a node correspond:
                //                     vvvv vvvv
                // FD00:0000:0000:0000:0000:0000:0000:0000
                let discriminator = match self.ipv6_allocation_range {
                    Some(range) => range.network().octets()[11],
                    None => global_ipv4.octets()[3],
                };
                let range = Ipv4Net::new_assert(Ipv4Addr::new(10, discriminator, 0, 0), 16);
                info!(v4_prefix = %range, "using autogenerated IPv4 allocation range");
                self.ipv4_allocation_range = Some(range);
            }
        }

        if config.enable_ipv6 {
            if self.ipv6_address.is_none() {
                let address = match network_provisioner
                    .first_global_ipv6(device, self.ipv6_router_address)
                    .await
                {
                    Ok(address) => address,
                    Err(err) => {
                        warn!(
                            %err,
                            fallback = %DEFAULT_IPV6_HOST_ADDRESS,
                            "no global IPv6 address found, using fallback node address"
                        );
                        DEFAULT_IPV6_HOST_ADDRESS
                    }
                };
                self.ipv6_address = Some(address);
            }

            if self.ipv6_allocation_range.is_none()
                && let Some(ipv4_range) = self.ipv4_allocation_range
            {
                let range =
                    ipv6_range_from_ipv4_range(config.ipv6_cluster_alloc_cidr_base, ipv4_range);
                info!(v6_prefix = %range, "using autogenerated IPv6 allocation range");
                self.ipv6_allocation_range = Some(range);
            }
        }

        Ok(())
    }
}

/// `<base>:<ipv4 network address>:0:0/96`, e.g. `f00d::a01:0:0:0/96` for
/// base `f00d::` and `10.1.0.0/16`.
fn ipv6_range_from_ipv4_range(base: Ipv6Prefix64, ipv4_range: Ipv4Net) -> Ipv6Net {
    let [a, b, c, d] = ipv4_range.network().octets();
    let mut segments = base.addr().segments();
    segments[4] = u16::from_be_bytes([a, b]);
    segments[5] = u16::from_be_bytes([c, d]);
    Ipv6Net::new_assert(Ipv6Addr::from(segments), 96)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::config::DEFAULT_IPV6_CLUSTER_ALLOC_CIDR_BASE;

    #[test]
    fn ipv6_range_embeds_the_ipv4_network_address() {
        let range = ipv6_range_from_ipv4_range(
            DEFAULT_IPV6_CLUSTER_ALLOC_CIDR_BASE,
            "10.42.0.0/16".parse().unwrap(),
        );
        assert_eq!(range, "f00d::a2a:0:0:0/96".parse::<Ipv6Net>().unwrap());
    }

    #[test]
    fn default_ipv6_host_address_matches_its_textual_form() {
        assert_eq!(
            DEFAULT_IPV6_HOST_ADDRESS,
            "fc00::10ca:1".parse::<Ipv6Addr>().unwrap()
        );
    }
}
