use std::{
    env::home_dir,
    fmt,
    net::{Ipv4Addr, Ipv6Addr},
    path::PathBuf,
    time::Duration,
};

use config::{Config as ConfigLoader, Environment, File};
use sarena_infra::is_global_unicast;
use sarena_utils::LogFormat;
use serde::Deserialize;

use crate::cli::Cli;

pub const DEFAULT_RUNTIME_PATH: &str = "/var/run/sarena";

/// Default for [`Config::ipv6_cluster_alloc_cidr_base`].
pub const DEFAULT_IPV6_CLUSTER_ALLOC_CIDR_BASE: Ipv6Prefix64 =
    Ipv6Prefix64(Ipv6Addr::new(0xf00d, 0, 0, 0, 0, 0, 0, 0));

/// The upper 64 bits of an IPv6 range: an address whose lower 64 bits are
/// zero, which construction (and deserialization) enforces.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Deserialize)]
#[serde(try_from = "Ipv6Addr")]
pub struct Ipv6Prefix64(Ipv6Addr);

impl Ipv6Prefix64 {
    pub const fn addr(self) -> Ipv6Addr {
        self.0
    }
}

impl TryFrom<Ipv6Addr> for Ipv6Prefix64 {
    type Error = String;

    fn try_from(addr: Ipv6Addr) -> Result<Self, Self::Error> {
        if addr.segments()[4..].iter().any(|&segment| segment != 0) {
            return Err(format!(
                "{addr} must have its lower 64 bits zero (e.g. `f00d::`)"
            ));
        }
        Ok(Self(addr))
    }
}

impl fmt::Display for Ipv6Prefix64 {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        self.0.fmt(f)
    }
}

/// Effective daemon configuration, merged from (lowest to highest precedence):
/// the config file (`--config <path>`, or `~/.sarena/sarena-daemon.{toml,json,yaml,yml}`
/// when it exists), `SARENA_<FIELD>` environment variables (e.g. `SARENA_SOCKET_PATH`),
/// and finally the command-line flags.
#[derive(Debug, Clone)]
pub struct Config {
    /// Emit debug-level log messages.
    pub debug: bool,

    /// Write logs to this file instead of stderr.
    pub log_file: Option<String>,

    /// Log output format: `text` (default) or `json`.
    pub log_format: LogFormat,

    /// BPF filesystem directory under which the datapath's maps and programs
    /// are pinned. Default: `/sys/fs/bpf/sarena`.
    pub pin_root: PathBuf,

    /// Base directory for the daemon's runtime files. Used to derive the
    /// defaults of `statedir_path` and `socket_path`. Default: `/var/run/sarena`.
    pub runtime_path: PathBuf,

    /// Directory where per-endpoint state is persisted, so endpoints can be
    /// restored after a daemon restart. Default: `<runtime_path>/state`.
    pub statedir_path: PathBuf,

    /// Unix domain socket the API server listens on (the CNI plugin and CLI
    /// connect to it). Default: `<runtime_path>/sarena.sock`.
    pub socket_path: PathBuf,

    /// True when IPv4 is enabled
    pub enable_ipv4: bool,

    /// True when IPv6 is enabled
    pub enable_ipv6: bool,

    /// Upper 64 bits of the IPv6 allocation range autogenerated from the
    /// IPv4 one (`<base>:<ipv4 network>:0:0/96`). Default: `f00d::`.
    pub ipv6_cluster_alloc_cidr_base: Ipv6Prefix64,

    /// IPv4 address of this node (its external address), overriding the one
    /// autodetected from the system's addresses. Must be a global unicast
    /// address (see [`is_global_unicast`]). Default: autodetected.
    pub ipv4_node_address: Option<Ipv4Addr>,

    /// IPv6 address of this node, overriding the one autodetected from the
    /// system's addresses. Must be a global unicast address (see
    /// [`is_global_unicast`]). Default: autodetected.
    pub ipv6_node_address: Option<Ipv6Addr>,

    /// Kubernetes API server URL. `https://` URLs authenticate with the
    /// in-cluster service account. Default: from the kubeconfig, or the
    /// in-cluster configuration.
    pub k8s_api_server_url: Option<String>,

    /// Kubeconfig file to connect to Kubernetes with; takes precedence over
    /// `k8s_api_server_url`. Default: `$KUBECONFIG` or `~/.kube/config` when
    /// present, the in-cluster configuration otherwise.
    pub k8s_kubeconfig_path: Option<PathBuf>,

    /// Timeout for connecting to and getting a response from the Kubernetes
    /// API server, and the interval of its heartbeat. Configured in seconds
    /// as `k8s_heartbeat_timeout_secs`, where `0` disables both. Default: 30 s.
    pub k8s_heartbeat_timeout: Option<Duration>,
}

#[derive(Deserialize)]
struct ConfigBuilder {
    #[serde(default)]
    debug: bool,

    #[serde(default)]
    log_file: Option<String>,

    #[serde(default)]
    log_format: LogFormat,

    #[serde(default = "default_pin_root")]
    pin_root: PathBuf,

    #[serde(default = "default_runtime_path")]
    runtime_path: PathBuf,

    statedir_path: Option<PathBuf>,
    socket_path: Option<PathBuf>,
    enable_ipv4: Option<bool>,
    enable_ipv6: Option<bool>,

    #[serde(default = "default_ipv6_cluster_alloc_cidr_base")]
    ipv6_cluster_alloc_cidr_base: Ipv6Prefix64,

    ipv4_node_address: Option<Ipv4Addr>,
    ipv6_node_address: Option<Ipv6Addr>,

    k8s_api_server_url: Option<String>,
    k8s_kubeconfig_path: Option<PathBuf>,

    #[serde(default = "default_k8s_heartbeat_timeout_secs")]
    k8s_heartbeat_timeout_secs: u64,
}

fn default_pin_root() -> PathBuf {
    PathBuf::from(sarena_data_plane::PIN_ROOT)
}

fn default_runtime_path() -> PathBuf {
    PathBuf::from(DEFAULT_RUNTIME_PATH)
}

const fn default_ipv6_cluster_alloc_cidr_base() -> Ipv6Prefix64 {
    DEFAULT_IPV6_CLUSTER_ALLOC_CIDR_BASE
}

const fn default_k8s_heartbeat_timeout_secs() -> u64 {
    sarena_kubernetes::client::DEFAULT_HEARTBEAT_TIMEOUT.as_secs()
}

impl TryFrom<ConfigBuilder> for Config {
    type Error = anyhow::Error;

    fn try_from(config: ConfigBuilder) -> anyhow::Result<Self> {
        let enable_ipv4 = config.enable_ipv4.unwrap_or(true);
        let enable_ipv6 = config.enable_ipv6.unwrap_or(false);
        if !enable_ipv4 && !enable_ipv6 {
            anyhow::bail!("IPv4 and/or IPv6 addressing must be enabled");
        }

        if let Some(ip) = config.ipv4_node_address
            && !is_global_unicast(&ip.into())
        {
            anyhow::bail!("ipv4_node_address {ip} is not a global unicast address");
        }
        if let Some(ip) = config.ipv6_node_address
            && !is_global_unicast(&ip.into())
        {
            anyhow::bail!("ipv6_node_address {ip} is not a global unicast address");
        }

        let statedir_path = config
            .statedir_path
            .unwrap_or_else(|| config.runtime_path.join("state"));
        let socket_path = config
            .socket_path
            .unwrap_or_else(|| config.runtime_path.join("sarena.sock"));
        Ok(Self {
            debug: config.debug,
            log_file: config.log_file,
            log_format: config.log_format,
            pin_root: config.pin_root,
            runtime_path: config.runtime_path,
            statedir_path,
            socket_path,
            enable_ipv4,
            enable_ipv6,
            ipv6_cluster_alloc_cidr_base: config.ipv6_cluster_alloc_cidr_base,
            ipv4_node_address: config.ipv4_node_address,
            ipv6_node_address: config.ipv6_node_address,
            k8s_api_server_url: config.k8s_api_server_url,
            k8s_kubeconfig_path: config.k8s_kubeconfig_path,
            k8s_heartbeat_timeout: (config.k8s_heartbeat_timeout_secs != 0)
                .then(|| Duration::from_secs(config.k8s_heartbeat_timeout_secs)),
        })
    }
}

pub fn load_config(cli: &Cli) -> anyhow::Result<Config> {
    let mut builder = ConfigLoader::builder();

    if let Some(path) = &cli.config {
        builder = builder.add_source(File::from(path.clone()));
    } else if let Some(home) = home_dir() {
        let path = ["toml", "json", "yaml", "yml"]
            .iter()
            .map(|ext| home.join(".sarena").join(format!("sarena-daemon.{ext}")))
            .find(|path| path.is_file());
        if let Some(path) = path {
            builder = builder.add_source(File::from(path));
        }
    }

    builder = builder.add_source(Environment::with_prefix("SARENA"));

    let config: ConfigBuilder = builder.build()?.try_deserialize()?;
    let mut config = Config::try_from(config)?;

    if cli.debug {
        config.debug = true;
    }

    if cli.log_file.is_some() {
        config.log_file.clone_from(&cli.log_file);
    }

    if let Some(log_format) = &cli.log_format {
        config.log_format = log_format.parse().map_err(|e: String| anyhow::anyhow!(e))?;
    }

    Ok(config)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn prefix(addr: &str) -> Result<Ipv6Prefix64, String> {
        Ipv6Prefix64::try_from(addr.parse::<Ipv6Addr>().unwrap())
    }

    #[test]
    fn ipv6_prefix64_requires_lower_64_bits_zero() {
        assert!(prefix("f00d::").is_ok());
        assert!(prefix("f00d:1:2:3::").is_ok());
        assert!(prefix("f00d::1").is_err());
        assert!(prefix("f00d::1:0:0:0").is_err());
    }

    #[test]
    fn ipv6_prefix64_is_validated_when_deserialized() {
        let ok: Ipv6Prefix64 = serde_json::from_str(r#""f00d::""#).unwrap();
        assert_eq!(ok, DEFAULT_IPV6_CLUSTER_ALLOC_CIDR_BASE);
        assert!(serde_json::from_str::<Ipv6Prefix64>(r#""f00d::1""#).is_err());
    }
}
